/**
 * Creates a localization function for the requested language.
 * @param {string} locale Requested locale code.
 * @returns {(key: string) => string} Translation lookup.
 */
export function createTranslator(locale) {
  const dictionary = messages[locale] ?? messages.en;
  return (key) => dictionary[key] ?? messages.en[key] ?? key;
}
